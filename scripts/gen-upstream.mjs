// gen-upstream — regenerate the two data files truffle-ts copies from the Go
// suite's shared `spore-host/libs` module, instead of hand-editing them:
//
//   src/metadata/apps.generated.ts       ← libs/catalog/catalog.yaml
//   src/data/static-prices.generated.ts  ← libs/pricing/ec2.go (EC2Pricing + PricesAsOf)
//
// Hand-maintained copies drifted (#30: every app description differed, the
// aliases were dropped so `find("imagej")` stopped resolving, chimerax lost its
// high-VRAM family). A generator plus a drift check makes the copy mechanical.
//
// Usage:
//   node scripts/gen-upstream.mjs --libs <dir>            # write both files
//   node scripts/gen-upstream.mjs --libs <dir> --check    # exit 1 if they differ
//
// <dir> is a libs checkout or module-cache directory, e.g.
//   "$(go env GOMODCACHE)/github.com/spore-host/libs@v0.51.2"
// The version is read from a `libs@vX.Y.Z` directory name, else from --version.
// No network, no AWS: it reads two files and writes two files.

import { readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const root = fileURLToPath(new URL("..", import.meta.url));
export const APPS_OUT = join(root, "src/metadata/apps.generated.ts");
export const PRICES_OUT = join(root, "src/data/static-prices.generated.ts");

/**
 * Static-table entries we have evidence are stale, excluded rather than copied.
 * Excluding is the #114 rule applied to our own copy: an absent price is a state
 * every caller handles, a wrong one is indistinguishable from a right one.
 * Each entry names its evidence; remove it once libs is refreshed.
 */
export const KNOWN_STALE = {
  "us-east-1": {
    // libs v0.51.2 carries 32.77 (a pre-2025-price-cut rate). The live Price List
    // returned 21.9576 for truffle-ts's catalog pull (2026-07) and again on
    // 2026-08-01 (truffle-ts #39). Filed upstream as spore-host/libs#67.
    "p4d.24xlarge": "libs has 32.77; live Price List 21.9576 (2026-07, 2026-08-01)",
  },
};

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

export function libsVersion(dir, explicit) {
  if (explicit) return explicit;
  const m = basename(dir).match(/^libs@(v\d+\.\d+\.\d+.*)$/);
  if (!m) throw new Error(`cannot tell the libs version from "${dir}"; pass --version vX.Y.Z`);
  return m[1];
}

/** The hardware-relevant subset of libs catalog.AppEntry, in catalog order. */
export function appsFromYaml(text) {
  const doc = parseYaml(text);
  if (!Array.isArray(doc?.apps)) throw new Error("catalog.yaml: no `apps:` list");
  return doc.apps.map((a) => {
    const e = {
      name: a.name,
      description: a.description ?? "",
      kind: a.kind ?? "application",
      instanceFamilies: a.instance_families ?? [],
    };
    if (a.high_vram_families?.length) e.highVramFamilies = a.high_vram_families;
    e.minVcpus = a.min_vcpus ?? 0;
    e.minMemoryGiB = a.min_memory_gib ?? 0;
    e.gpu = a.gpu === true;
    if (a.min_vram_gib) e.minVramGiB = a.min_vram_gib;
    e.aliases = (a.aliases ?? []).map((s) => String(s).toLowerCase());
    if (a.license) e.license = a.license;
    return e;
  });
}

/** EC2Pricing (region → type → $/hr) and PricesAsOf, parsed from libs pricing/ec2.go. */
export function pricesFromGo(text) {
  const asOf = text.match(/const PricesAsOf = "(\d{4}-\d{2}-\d{2})"/)?.[1];
  if (!asOf) throw new Error("ec2.go: no PricesAsOf");
  const start = text.indexOf("var EC2Pricing");
  const end = text.indexOf("\n}\n", start);
  if (start < 0 || end < 0) throw new Error("ec2.go: no EC2Pricing table");
  const body = text.slice(start, end);
  const table = {};
  let region;
  for (const line of body.split("\n")) {
    const r = line.match(/^\s*"([a-z0-9-]+)":\s*\{/);
    if (r) {
      region = r[1];
      table[region] = {};
      continue;
    }
    for (const m of line.matchAll(/"([a-z0-9.-]+)":\s*([0-9.]+)/g)) {
      if (!region) throw new Error(`ec2.go: price before any region: ${line}`);
      const price = Number(m[2]);
      if (!(price > 0)) throw new Error(`ec2.go: non-positive price ${m[1]}=${m[2]}`);
      table[region][m[1]] = price;
    }
  }
  if (Object.keys(table).length === 0) throw new Error("ec2.go: parsed an empty table");
  return { asOf, table };
}

const HEADER = (src, version) =>
  `// GENERATED by scripts/gen-upstream.mjs from spore-host/libs ${version} ${src}.\n` +
  `// Do not edit by hand: regenerate with \`npm run gen:upstream -- --libs <dir>\`.\n`;

export function renderApps(apps, version) {
  return (
    HEADER("catalog/catalog.yaml", version) +
    `\nimport type { AppEntry } from "./apps.js";\n\n` +
    `/** The libs version this catalog was generated from. */\n` +
    `export const APP_CATALOG_SOURCE = ${JSON.stringify(`spore-host/libs ${version}`)};\n\n` +
    `/** Every app in the upstream catalog, in catalog order. */\n` +
    `export const UPSTREAM_APPS: readonly AppEntry[] = ${JSON.stringify(apps, null, 2)};\n`
  );
}

export function renderPrices({ asOf, table }, version) {
  const kept = {};
  const excluded = [];
  for (const [region, prices] of Object.entries(table)) {
    kept[region] = {};
    for (const [type, price] of Object.entries(prices)) {
      const why = KNOWN_STALE[region]?.[type];
      if (why) excluded.push(`//   ${region} ${type}: ${why}`);
      else kept[region][type] = price;
    }
  }
  const lines = Object.entries(kept).map(([region, prices]) => {
    const body = Object.entries(prices)
      .map(([t, p]) => `    ${JSON.stringify(t)}: ${p},`)
      .join("\n");
    return `  ${JSON.stringify(region)}: {\n${body}\n  },`;
  });
  return (
    HEADER("pricing/ec2.go", version) +
    (excluded.length
      ? `//\n// Excluded as known-stale (scripts/gen-upstream.mjs KNOWN_STALE):\n${excluded.join("\n")}\n`
      : "") +
    `\n/** When the rates below were fetched from the Price List API (libs PricesAsOf). */\n` +
    `export const STATIC_PRICES_AS_OF = ${JSON.stringify(asOf)};\n\n` +
    `/** Where the rates below came from. */\n` +
    `export const STATIC_PRICES_SOURCE = ${JSON.stringify(`spore-host/libs ${version} pricing.EC2Pricing`)};\n\n` +
    `/** On-Demand $/hr (Linux, shared tenancy) by region, then instance type. */\n` +
    `export const STATIC_EC2_PRICES: Readonly<Record<string, Readonly<Record<string, number>>>> = {\n` +
    lines.join("\n") +
    `\n};\n`
  );
}

function main() {
  const dir = arg("--libs") ?? process.env.TRUFFLE_LIBS_DIR;
  if (!dir) {
    console.error("usage: gen-upstream.mjs --libs <libs dir> [--version vX.Y.Z] [--check]");
    process.exit(2);
  }
  const version = libsVersion(dir, arg("--version"));
  const apps = renderApps(appsFromYaml(readFileSync(join(dir, "catalog/catalog.yaml"), "utf8")), version);
  const prices = renderPrices(pricesFromGo(readFileSync(join(dir, "pricing/ec2.go"), "utf8")), version);

  if (process.argv.includes("--check")) {
    const drift = [];
    if (readFileSync(APPS_OUT, "utf8") !== apps) drift.push(APPS_OUT);
    if (readFileSync(PRICES_OUT, "utf8") !== prices) drift.push(PRICES_OUT);
    if (drift.length) {
      console.error(`out of date against libs ${version}:\n  ${drift.join("\n  ")}\nrun: npm run gen:upstream -- --libs ${dir}`);
      process.exit(1);
    }
    console.log(`up to date with libs ${version}`);
    return;
  }
  writeFileSync(APPS_OUT, apps);
  writeFileSync(PRICES_OUT, prices);
  console.log(`wrote ${APPS_OUT}\nwrote ${PRICES_OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
